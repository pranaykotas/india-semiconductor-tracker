# Pre-render step: record when the tracker data last changed, for the site footer.
# Writes _variables.yml with `data_updated`, used in _quarto.yml as {{< var data_updated >}}.
# Uses the date of the last git commit touching data/; falls back to today if git is unavailable.

last <- tryCatch(
  system2("git", c("log", "-1", "--date=short", "--format=%cd", "--", "data/"), stdout = TRUE, stderr = FALSE),
  error = function(e) character(0)
)
d <- if (length(last) == 1 && grepl("^\\d{4}-\\d{2}-\\d{2}$", last)) as.Date(last) else Sys.Date()

writeLines(
  c("# Auto-generated by R/write_data_date.R at render time. Do not edit.",
    sprintf('data_updated: "%s"', format(d, "%d %B %Y"))),
  "_variables.yml"
)
